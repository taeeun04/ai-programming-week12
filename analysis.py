import pandas as pd


def 정제(df):
    # 원본 df를 바꾸지 않도록 복사본을 만든다
    결과 = df.copy()
    print("처음 행 수:", len(결과))

    # 1) 점수가 비어 있는 행을 삭제한다
    결과 = 결과.dropna(subset=["점수"])
    print("1) 점수 빈 행 삭제 후:", len(결과))

    # 2) 모든 열이 완전히 같은 중복 행은 하나만 남긴다
    결과 = 결과.drop_duplicates()
    print("2) 중복 행 삭제 후:", len(결과))

    # 3) 반과 과목 값의 앞뒤 공백을 제거한다
    결과["반"] = 결과["반"].str.strip()
    결과["과목"] = 결과["과목"].str.strip()
    print("3) 공백 제거 후:", len(결과))

    # 4) 점수가 0 이상 100 이하인 행만 남기고, 점수를 정수형으로 바꾼다
    결과 = 결과[(결과["점수"] >= 0) & (결과["점수"] <= 100)]
    결과["점수"] = 결과["점수"].astype(int)
    print("4) 점수 범위 밖 행 삭제 후:", len(결과))

    # 행 번호를 0부터 다시 매긴다
    결과 = 결과.reset_index(drop=True)
    return 결과


# 사용 예시: 학번이 숫자로 읽히지 않도록 문자형으로 지정한다
df = pd.read_csv("scores_2026.csv", dtype={"학번": str})
정제된_df = 정제(df)

# 필터링(프롬프트B) - 과목이 수학인 행만 남긴다
수학_df = 정제된_df[정제된_df["과목"] == "수학"]
print("과목이 수학인 행 수:", len(수학_df))

# 그룹화(프롬프트C)
# '반'으로 묶어 점수 평균을 낸다
반별_평균 = 정제된_df.groupby("반")["점수"].mean()
print(반별_평균)

# '과목'과 '반' 두 기준으로 묶어 점수 평균을 낸다
과목_반별_평균 = 정제된_df.groupby(["과목", "반"])["점수"].mean()
print(과목_반별_평균)

def 반별평균(df):
    # '반'으로 묶어 점수의 개수, 평균, 중앙값, 최댓값을 한 표로 만든다
    표 = df.groupby("반")["점수"].agg(["count", "mean", "median", "max"])

    # 열 이름을 한글로 바꾼다
    표.columns = ["개수", "평균", "중앙값", "최댓값"]

    # 소수 둘째 자리까지 반올림한다
    표 = 표.round(2)
    print(표)

    # 반 이름이 키인 평균값 Series를 반환한다
    return 표["평균"]


